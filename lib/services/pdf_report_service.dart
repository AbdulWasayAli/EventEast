import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/event_model.dart';

class PdfReportService {
  static Future<void> generateAndExportReport({
    required int totalUsers,
    required List<EventModel> events,
    required int pendingApprovalsCount,
    required int flaggedItemsCount,
  }) async {
    final pdf = pw.Document();
    double totalRevenue = events.fold(0.0, (sum, e) => sum + (e.price * 150));

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (pw.Context context) {
          return pw.Column(
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'EventEase',
                        style: pw.TextStyle(
                          fontSize: 24,
                          fontWeight: pw.FontWeight.bold,
                          color: PdfColor.fromHex('#007E7B'),
                        ),
                      ),
                      pw.Text(
                        'Executive Analytics & Platform Report',
                        style: const pw.TextStyle(
                          fontSize: 12,
                          color: PdfColors.grey700,
                        ),
                      ),
                    ],
                  ),
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.end,
                    children: [
                      pw.Text(
                        'Date: ${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                        style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
                      ),
                      pw.Text(
                        'Generated by: Super Admin',
                        style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
                      ),
                    ],
                  ),
                ],
              ),
              pw.Divider(thickness: 1.5, color: PdfColor.fromHex('#007E7B')),
              pw.SizedBox(height: 10),
            ],
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(top: 20),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  '© 2026 EventEase Technologies - Confidential',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
                ),
              ],
            ),
          );
        },
        build: (pw.Context context) {
          return [
            pw.SizedBox(height: 10),
            pw.Text(
              'System Summary Overview',
              style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColor.fromHex('#1E293B')),
            ),
            pw.SizedBox(height: 12),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                _buildSummaryBox('Total Users', '$totalUsers', PdfColor.fromHex('#028090')),
                _buildSummaryBox('Active Events', '${events.length}', PdfColor.fromHex('#00A896')),
                _buildSummaryBox('Est. Revenue', 'Rs. ${totalRevenue.toStringAsFixed(0)}', PdfColor.fromHex('#10B981')),
                _buildSummaryBox('Pending Queue', '$pendingApprovalsCount', PdfColor.fromHex('#F59E0B')),
              ],
            ),

            pw.SizedBox(height: 24),
            pw.Text(
              'Top Performing Events List',
              style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColor.fromHex('#1E293B')),
            ),
            pw.SizedBox(height: 12),
            pw.TableHelper.fromTextArray(
              headers: ['Rank', 'Event Title', 'Category', 'Organizer', 'Estimated Sales', 'Status'],
              data: List.generate(events.length, (index) {
                final e = events[index];
                return [
                  '#${index + 1}',
                  e.title,
                  e.category,
                  e.organizer,
                  'Rs. ${((index + 1) * 14500).toStringAsFixed(0)}',
                  'Active',
                ];
              }),
              headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white, fontSize: 10),
              headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#007E7B')),
              rowDecoration: const pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey200))),
              cellPadding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
              cellAlignments: {
                0: pw.Alignment.centerLeft,
                1: pw.Alignment.centerLeft,
                2: pw.Alignment.center,
                3: pw.Alignment.centerLeft,
                4: pw.Alignment.centerRight,
                5: pw.Alignment.center,
              },
            ),

            pw.SizedBox(height: 24),
            pw.Text(
              'Platform Metrics Breakdown',
              style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColor.fromHex('#1E293B')),
            ),
            pw.SizedBox(height: 12),

            pw.TableHelper.fromTextArray(
              headers: ['Metric Name', 'Current Count', 'Monthly Growth', 'Health Status'],
              data: [
                ['Total Registered Attendees', '${(totalUsers * 0.8).toInt()}', '+12.4%', 'Optimal'],
                ['Verified Organizers', '${(totalUsers * 0.2).toInt()}', '+4.8%', 'Optimal'],
                ['Flagged Moderation Queue', '$flaggedItemsCount', '-5.0%', 'Attention Needed'],
                ['Pending Approval Queue', '$pendingApprovalsCount', 'N/A', 'Action Required'],
              ],
              headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white, fontSize: 10),
              headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#0F172A')),
              cellPadding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
            ),
          ];
        },
      ),
    );
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: 'EventEase_Admin_Report_${DateTime.now().millisecondsSinceEpoch}.pdf',
    );
  }

  static pw.Widget _buildSummaryBox(String title, String value, PdfColor color) {
    return pw.Container(
      width: 110,
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        color: PdfColors.white,
        borderRadius: pw.BorderRadius.circular(8),
        border: pw.Border.all(color: color, width: 1),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(title, style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey700)),
          pw.SizedBox(height: 4),
          pw.Text(value, style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: color)),
        ],
      ),
    );
  }
}
